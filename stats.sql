CREATE TABLE IF NOT EXISTS salts (day TEXT PRIMARY KEY, salt TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS visitors (day TEXT NOT NULL, id TEXT NOT NULL, n INTEGER NOT NULL, PRIMARY KEY (day, id));
CREATE TABLE IF NOT EXISTS totals (day TEXT PRIMARY KEY, visitors INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS hits (day TEXT NOT NULL, path TEXT NOT NULL, n INTEGER NOT NULL, PRIMARY KEY (day, path));
CREATE TABLE IF NOT EXISTS refs (day TEXT NOT NULL, ref TEXT NOT NULL, n INTEGER NOT NULL, PRIMARY KEY (day, ref));
CREATE TABLE IF NOT EXISTS events (day TEXT NOT NULL, name TEXT NOT NULL, n INTEGER NOT NULL, PRIMARY KEY (day, name));
